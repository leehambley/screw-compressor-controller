//! ST7701S panel controller setup over its 3-wire, 9-bit SPI (bit-banged:
//! it only runs once at boot). Sequence and settings from ESPHome's tested
//! `WAVESHARE-4-480X480` mipi_rgb model (base ST7701S table, SPI mode 3,
//! 18-bit pixel mode, colour inversion on).

use embassy_time::{Delay, Timer};
use embedded_hal::delay::DelayNs;
use esp_hal::gpio::Output;

const INIT: &[&[u8]] = &[
    &[0xFF, 0x77, 0x01, 0x00, 0x00, 0x10], // page 0
    &[0xC0, 0x3B, 0x00],
    &[0xC1, 0x0D, 0x02],
    &[0xC2, 0x31, 0x05],
    &[0xB0, 0x00, 0x11, 0x18, 0x0E, 0x11, 0x06, 0x07, 0x08, 0x07, 0x22, 0x04, 0x12, 0x0F, 0xAA, 0x31, 0x18],
    &[0xB1, 0x00, 0x11, 0x19, 0x0E, 0x12, 0x07, 0x08, 0x08, 0x08, 0x22, 0x04, 0x11, 0x11, 0xA9, 0x32, 0x18],
    &[0xFF, 0x77, 0x01, 0x00, 0x00, 0x11], // page 1
    &[0xB0, 0x60],
    &[0xB1, 0x32],
    &[0xB2, 0x07],
    &[0xB3, 0x80],
    &[0xB5, 0x49],
    &[0xB7, 0x85],
    &[0xB8, 0x21],
    &[0xC1, 0x78],
    &[0xC2, 0x78],
    &[0xE0, 0x00, 0x1B, 0x02],
    &[0xE1, 0x08, 0xA0, 0x00, 0x00, 0x07, 0xA0, 0x00, 0x00, 0x00, 0x44, 0x44],
    &[0xE2, 0x11, 0x11, 0x44, 0x44, 0xED, 0xA0, 0x00, 0x00, 0xEC, 0xA0, 0x00, 0x00],
    &[0xE3, 0x00, 0x00, 0x11, 0x11],
    &[0xE4, 0x44, 0x44],
    &[0xE5, 0x0A, 0xE9, 0xD8, 0xA0, 0x0C, 0xEB, 0xD8, 0xA0, 0x0E, 0xED, 0xD8, 0xA0, 0x10, 0xEF, 0xD8, 0xA0],
    &[0xE6, 0x00, 0x00, 0x11, 0x11],
    &[0xE7, 0x44, 0x44],
    &[0xE8, 0x09, 0xE8, 0xD8, 0xA0, 0x0B, 0xEA, 0xD8, 0xA0, 0x0D, 0xEC, 0xD8, 0xA0, 0x0F, 0xEE, 0xD8, 0xA0],
    &[0xEB, 0x02, 0x00, 0xE4, 0xE4, 0x88, 0x00, 0x40],
    &[0xEC, 0x3C, 0x00],
    &[0xED, 0xAB, 0x89, 0x76, 0x54, 0x02, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x20, 0x45, 0x67, 0x98, 0xBA],
    &[0xFF, 0x77, 0x01, 0x00, 0x00, 0x13], // page 3
    &[0xE5, 0xE4],
    &[0xFF, 0x77, 0x01, 0x00, 0x00, 0x10], // page 0
    &[0xCD, 0x08],
    // Tail as Waveshare's V4 demo sends it (ST7701 "type1").
    &[0xFF, 0x77, 0x01, 0x00, 0x00, 0x00], // leave the command2 pages
    &[0x21],       // INVON
    &[0x3A, 0x60], // COLMOD: 18-bit RGB interface
];

pub struct St7701 {
    pub cs: Output<'static>,
    pub sck: Output<'static>,
    pub sda: Output<'static>,
}

impl St7701 {
    /// Call after the panel's hardware reset has been released.
    pub async fn init(mut self) {
        self.cs.set_high();
        self.sck.set_high(); // mode 3: idle high
        for cmd in INIT {
            self.write(cmd);
        }
        self.write(&[0x11]); // SLPOUT
        Timer::after_millis(120).await;
        self.write(&[0x29]); // DISPON
        Timer::after_millis(20).await;
    }

    fn write(&mut self, cmd: &[u8]) {
        self.cs.set_low();
        for (i, &byte) in cmd.iter().enumerate() {
            // Ninth (leading) bit: 0 = command, 1 = parameter.
            self.bit(i != 0);
            for b in (0..8).rev() {
                self.bit(byte & (1 << b) != 0);
            }
        }
        self.cs.set_high();
        Delay.delay_us(2);
    }

    /// Data changes while SCK is low, panel samples on the rising edge.
    fn bit(&mut self, high: bool) {
        self.sck.set_low();
        if high { self.sda.set_high() } else { self.sda.set_low() }
        Delay.delay_ns(500); // 2 MHz max
        self.sck.set_high();
        Delay.delay_ns(500);
    }
}
